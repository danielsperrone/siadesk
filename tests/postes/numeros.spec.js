import { test, expect } from '@playwright/test'
import { sessaoIsolada } from './setup'

test('digitação negativa preserva sinal, vazio e decimal sem zerar a posição', async ({ page }) => {
  await sessaoIsolada(page)
  await page.goto('/', { waitUntil: 'domcontentloaded' })
  await page.waitForFunction(async () => (await import('/src/cloud/session.ts')).useSession.getState().ready)
  await page.evaluate(async () => {
    const { useProject } = await import('/src/store/project.ts')
    useProject.getState().criarNovoProjeto('Digitação de posições', 'Teste', 'NUMEROS')
    useProject.getState().setAbaAtiva('postes')
  })
  const config = () => page.evaluate(async () => (await import('/src/store/project.ts')).useProject.getState().config)
  const padrao = page.locator('label.checkbox').filter({ has: page.getByText('SIAP01', { exact: true }) }).locator('..')
  await padrao.getByRole('button', { name: 'Alterar', exact: true }).click()
  const x = padrao.getByLabel('Espaçamento Horizontal - X (m)', { exact: true })
  await x.fill('')
  expect((await config()).distanciaSiap01).toBe(6.5)
  await x.pressSequentially('-')
  expect((await config()).distanciaSiap01).toBe(6.5)
  await x.pressSequentially('2.5')
  await expect(x).toHaveValue('-2.5')
  expect((await config()).distanciaSiap01).toBe(-2.5)
  await x.press('Enter')
  await expect(x).toHaveValue('-2.5')
  await x.fill('')
  await x.press('Tab')
  await expect(x).toHaveValue('-2.5')

  await page.getByRole('button', { name: 'Adicionar poste', exact: true }).click()
  const adicional = page.getByLabel('Deslocamento longitudinal — X (m)', { exact: true })
  await adicional.fill('')
  await adicional.pressSequentially('-')
  expect((await config()).postesAdicionais[0].distanciaX).toBe(0)
  await adicional.pressSequentially('0.75')
  await expect(adicional).toHaveValue('-0.75')
  expect((await config()).postesAdicionais[0].distanciaX).toBe(-0.75)
  await adicional.fill('')
  await adicional.pressSequentially('-')
  await adicional.press('Tab')
  await expect(adicional).toHaveValue('-0.75')
  await adicional.press('ArrowUp')
  expect((await config()).postesAdicionais[0].distanciaX).toBeGreaterThan(-0.75)
  await page.screenshot({ path: 'test-results/postes/numeros.png' })
})
